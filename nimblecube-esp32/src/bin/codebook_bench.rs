//! Idea 5: is `FeatureEncoder::encode` replaceable by a flash-resident codebook?
//!
//! The encoder is frozen once seed and ranges are chosen, so all `L^CH` outputs
//! are known at build time. At CH=3, L=16 that is 4096 entries x 512 B = 2 MB,
//! against 16 MB of flash. Encoding would become an index into memory-mapped
//! flash instead of ~115 us of bind and bundle.
//!
//! The open question is whether reads from memory-mapped flash are fast enough:
//! if a 512-byte fetch costs more than the work it replaces, the idea dies here.
//!   cd nimblecube-esp32 && cargo run --release --bin codebook_bench

#![no_std]
#![no_main]

use core::hint::black_box;
use esp_backtrace as _;
use esp_hal::clock::CpuClock;
use esp_hal::delay::Delay;
use esp_hal::main;
use esp_hal::time::Instant;
use esp_println::println;

use nimblecube_core::encode::{quantize, FeatureEncoder};
use nimblecube_core::hv::{Hv, WORDS};

esp_bootloader_esp_idf::esp_app_desc!();

const CH: usize = 3;
const L: usize = 16;
const SEED: u64 = 7;
const RANGES: [(i32, i32); CH] = [(0, 4095), (0, 4095), (-4095, 4095)];
const ENTRIES: usize = L * L * L;
const BYTES: usize = ENTRIES * WORDS * 8;
const M: u64 = 200;

#[repr(align(8))]
struct Align8<T: ?Sized>(T);

/// The codebook, generated by `examples/gen_codebook.rs`, laid out as
/// `[Hv; ENTRIES]` at flat index `i*L*L + j*L + k`.
static CODEBOOK: &Align8<[u8; BYTES]> = &Align8(*include_bytes!("../../codebook.bin"));

/// `Hv` is a single-field tuple struct over `[u64; WORDS]`, so its layout is the
/// array's. Fine for a probe; a real version would make that guarantee explicit.
#[inline]
fn entry(idx: usize) -> &'static Hv {
    unsafe { &*(CODEBOOK.0.as_ptr() as *const Hv).add(idx) }
}

#[inline]
fn flat(feats: &[i32; CH]) -> usize {
    let mut idx = 0usize;
    for i in 0..CH {
        let (lo, hi) = RANGES[i];
        idx = idx * L + quantize(feats[i], lo, hi, L);
    }
    idx
}

fn xs(s: &mut u64) -> u64 {
    *s ^= *s << 13;
    *s ^= *s >> 7;
    *s ^= *s << 17;
    *s
}

#[main]
fn main() -> ! {
    let config = esp_hal::Config::default().with_cpu_clock(CpuClock::max());
    let _p = esp_hal::init(config);

    let enc = FeatureEncoder::<CH, L>::new(SEED, RANGES);
    let mut st: u64 = 0x1234_5678_9abc_def1;
    let mut q = Hv::zero();
    for w in q.0.iter_mut() {
        *w = xs(&mut st);
    }

    // representative feature value per level, same scan the generator used
    let mut reps = [[0i32; L]; CH];
    for c in 0..CH {
        let (lo, hi) = RANGES[c];
        let mut found = 0;
        let mut v = lo;
        let mut seen = [false; L];
        while v <= hi && found < L {
            let i = quantize(v, lo, hi, L);
            if !seen[i] {
                seen[i] = true;
                reps[c][i] = v;
                found += 1;
            }
            v += 1;
        }
    }

    // every entry must match the computed encoder, or the table is worthless
    let mut mismatch = 0u32;
    for i in 0..L {
        for j in 0..L {
            for k in 0..L {
                let f = [reps[0][i], reps[1][j], reps[2][k]];
                if *entry(flat(&f)) != enc.encode(&f) {
                    mismatch += 1;
                }
            }
        }
    }

    let probe: [[i32; CH]; 8] = core::array::from_fn(|n| {
        [reps[0][n * 2 % L], reps[1][(n * 5 + 1) % L], reps[2][(n * 7 + 3) % L]]
    });

    let mut acc = 0u64;
    for n in 0..64usize {
        acc = acc.wrapping_add(enc.encode(&probe[n % 8]).0[0]);
        acc = acc.wrapping_add(entry(flat(&probe[n % 8])).0[0]);
    }

    // --- computed encode, then the hamming a real query would do ---
    let t = Instant::now();
    for n in 0..M as usize {
        acc = acc.wrapping_add(enc.encode(black_box(&probe[n % 8])).hamming(&q) as u64);
    }
    let comp_ns = t.elapsed().as_micros() * 1000 / M;

    // --- codebook lookup, then the same hamming (touches all 64 words) ---
    let t = Instant::now();
    for n in 0..M as usize {
        acc = acc.wrapping_add(entry(flat(black_box(&probe[n % 8]))).hamming(&q) as u64);
    }
    let tab_ns = t.elapsed().as_micros() * 1000 / M;

    // --- reversed order, to rule out an ordering artifact ---
    let t = Instant::now();
    for n in 0..M as usize {
        acc = acc.wrapping_add(entry(flat(black_box(&probe[n % 8]))).hamming(&q) as u64);
    }
    let tab2_ns = t.elapsed().as_micros() * 1000 / M;

    let t = Instant::now();
    for n in 0..M as usize {
        acc = acc.wrapping_add(enc.encode(black_box(&probe[n % 8])).hamming(&q) as u64);
    }
    let comp2_ns = t.elapsed().as_micros() * 1000 / M;

    // --- lookup alone, touching one word: isolates index + first flash read ---
    let t = Instant::now();
    for n in 0..M as usize {
        acc = acc.wrapping_add(entry(flat(black_box(&probe[n % 8]))).0[0]);
    }
    let look_ns = t.elapsed().as_micros() * 1000 / M;

    // --- cold path: walk all 4096 entries so the flash cache cannot hold them.
    // The 2 MB codebook is far larger than the cache, so a real workload hitting
    // varied entries pays a cold read. The loops above cycle 8 entries and are a
    // warm-cache best case.
    const MC: u64 = 2000;
    let t = Instant::now();
    for n in 0..MC as usize {
        let idx = n.wrapping_mul(2_654_435_761) % ENTRIES;
        acc = acc.wrapping_add(entry(black_box(idx)).hamming(&q) as u64);
    }
    let cold_ns = t.elapsed().as_micros() * 1000 / MC;

    // same walk, but re-reading one hot entry, to isolate the cold-read premium
    let t = Instant::now();
    for _ in 0..MC {
        acc = acc.wrapping_add(entry(black_box(7)).hamming(&q) as u64);
    }
    let hot_ns = t.elapsed().as_micros() * 1000 / MC;

    // --- hamming alone, for reference ---
    let t = Instant::now();
    for _ in 0..M {
        acc = acc.wrapping_add(black_box(&q).hamming(black_box(&q)) as u64);
    }
    let ham_ns = t.elapsed().as_micros() * 1000 / M;

    black_box(acc);
    let delay = Delay::new();
    macro_rules! line {
        ($($a:tt)*) => {{ println!($($a)*); delay.delay_millis(25); }};
    }
    loop {
        line!("codebook_bench (ESP32-S3 @ 240 MHz)  CH={} L={} entries={}", CH, L, ENTRIES);
        line!("codebook: {} bytes in flash", BYTES);
        line!("mismatches vs computed encoder: {} (want 0)", mismatch);
        line!("--");
        line!("hamming alone            : {} ns", ham_ns);
        line!("codebook lookup alone    : {} ns", look_ns);
        line!("computed encode + hamming: {} ns  (rerun {})", comp_ns, comp2_ns);
        line!("codebook   look + hamming: {} ns  (rerun {})", tab_ns, tab2_ns);
        line!("codebook cold walk + hamming: {} ns (all {} entries)", cold_ns, ENTRIES);
        line!("codebook hot entry  + hamming: {} ns", hot_ns);
        line!("checksum={}", acc);
        delay.delay_millis(3000);
    }
}
